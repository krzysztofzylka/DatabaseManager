<?php

namespace krzysztofzylka\DatabaseManager\Dialect;

use krzysztofzylka\DatabaseManager\Column;
use krzysztofzylka\DatabaseManager\DatabaseConnect;
use krzysztofzylka\DatabaseManager\Enum\Trigger;
use krzysztofzylka\DatabaseManager\Exception\ConnectException;
use PDO;
use PDOStatement;

/**
 * Everything that differs between database engines, so the rest of the library
 * never has to branch on DatabaseType
 */
interface DatabaseDialect
{

    /**
     * Create a PDO connection for the given configuration
     * @param DatabaseConnect $connect
     * @return PDO
     * @throws ConnectException
     */
    public function createPdo(DatabaseConnect $connect): PDO;

    /**
     * Character used to quote identifiers
     * @return string
     */
    public function getIdentifierQuote(): string;

    /**
     * Quote an identifier, quoting each segment of a qualified name (table.column) separately
     * @param string $name
     * @return string
     */
    public function quoteIdentifier(string $name): string;

    /**
     * Column definition used in CREATE TABLE / ALTER TABLE ADD
     * @param Column $column
     * @return string
     */
    public function columnDefinition(Column $column): string;

    /**
     * Table-level PRIMARY KEY clause for the column, or null when the key is declared inline
     * @param Column $column
     * @return ?string
     */
    public function primaryKeyClause(Column $column): ?string;

    /**
     * Trigger statement for a column trigger, or null when the engine does not support it
     * @param Trigger $trigger
     * @param string $tableName
     * @param string $columnName
     * @return ?string
     */
    public function triggerSql(Trigger $trigger, string $tableName, string $columnName): ?string;

    /**
     * CREATE TABLE statement
     * @param string $tableName
     * @param array $columnDefinitions
     * @param array $constraints table-level clauses appended after the columns
     * @return string
     */
    public function createTableSql(string $tableName, array $columnDefinitions, array $constraints = []): string;

    /**
     * Clause appended to INSERT so the generated id can be read back ('' when not needed)
     * @return string
     */
    public function insertReturningClause(): string;

    /**
     * Read the id generated by an executed INSERT
     * @param PDOStatement $statement
     * @param PDO $pdo
     * @return mixed
     */
    public function lastInsertId(PDOStatement $statement, PDO $pdo): mixed;

    /**
     * Column list in the MySQL DESCRIBE shape (Field, Type, Null, Key, Default, Extra)
     * @param PDO $pdo
     * @param string $tableName
     * @return array
     */
    public function columnList(PDO $pdo, string $tableName): array;

    /**
     * Whether the table exists
     * @param PDO $pdo
     * @param string $tableName
     * @return bool
     */
    public function tableExists(PDO $pdo, string $tableName): bool;

    /**
     * Names of all tables
     * @param PDO $pdo
     * @return array
     */
    public function listTables(PDO $pdo): array;

    /**
     * Column details of all tables, keyed by table name
     * @param PDO $pdo
     * @return array
     */
    public function tableDetails(PDO $pdo): array;

    /**
     * Whether the column has a single-column UNIQUE constraint
     * @param PDO $pdo
     * @param string $tableName
     * @param string $columnName
     * @return bool
     */
    public function isColumnUnique(PDO $pdo, string $tableName, string $columnName): bool;

}
